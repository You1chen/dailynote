#!/usr/bin/env bash
# Ji Android signing key generator.
# Generates android/ji-release.jks and android/keystore.properties.
# Both files are gitignored; never commit them.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
OUTPUT_DIR="$SCRIPT_DIR/../android"
KEYSTORE_FILE="$OUTPUT_DIR/ji-release.jks"
PROPS_FILE="$OUTPUT_DIR/keystore.properties"

if [ -n "${JAVA_HOME:-}" ] && [ -x "$JAVA_HOME/bin/keytool" ]; then
  KEYTOOL="$JAVA_HOME/bin/keytool"
elif command -v keytool >/dev/null 2>&1; then
  KEYTOOL="$(command -v keytool)"
elif [ -x "/Applications/Android Studio.app/Contents/jbr/Contents/Home/bin/keytool" ]; then
  KEYTOOL="/Applications/Android Studio.app/Contents/jbr/Contents/Home/bin/keytool"
elif [ -x "$HOME/Android/Sdk/platform-tools/keytool" ]; then
  KEYTOOL="$HOME/Android/Sdk/platform-tools/keytool"
else
  echo "keytool not found. Install a JDK or set JAVA_HOME, then retry." >&2
  exit 1
fi

if [ -f "$KEYSTORE_FILE" ]; then
  read -r -p "Keystore already exists. Overwrite? (y/N): " CONFIRM
  case "$CONFIRM" in
    y|Y) ;;
    *) echo "Cancelled."; exit 0 ;;
  esac
fi

if [ -n "${DAILYNOTE_STOREPASS:-}" ]; then
  STOREPASS="$DAILYNOTE_STOREPASS"
else
  if [ ! -t 0 ]; then
    echo "Set DAILYNOTE_STOREPASS (and optionally DAILYNOTE_KEYPASS) for non-interactive use." >&2
    exit 1
  fi
  read -r -s -p "Keystore password: " STOREPASS
  echo
  read -r -s -p "Confirm password: " CONFIRM_PASS
  echo
  if [ "$STOREPASS" != "$CONFIRM_PASS" ]; then
    echo "Passwords do not match." >&2
    exit 1
  fi
fi
KEYPASS="${DAILYNOTE_KEYPASS:-$STOREPASS}"
ALIAS="${DAILYNOTE_KEY_ALIAS:-ji}"
VALIDITY=10000

"$KEYTOOL" -genkeypair -v \
  -keystore "$KEYSTORE_FILE" \
  -keyalg RSA \
  -keysize 2048 \
  -validity "$VALIDITY" \
  -alias "$ALIAS" \
  -storepass "$STOREPASS" \
  -keypass "$KEYPASS" \
  -dname "CN=Ji, OU=Development, O=Ji, C=CN"

cat > "$PROPS_FILE" <<EOF
# Generated by scripts/setup-keystore.sh. Do not commit this file.
storeFile=ji-release.jks
storePassword=$STOREPASS
keyAlias=$ALIAS
keyPassword=$KEYPASS
EOF

echo "Keystore: $KEYSTORE_FILE"
echo "Properties: $PROPS_FILE"
echo "Keep both files private; they are excluded by .gitignore."
